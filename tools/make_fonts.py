"""Convert JetBrains Mono into 1-bit GFX bitmap fonts for the firmware.

The UI is designed at 240x135 with text 10, 22, 28 and 36 pixels tall. One
font set is generated per UI scale (see UI_SCALE_NUM / UI_SCALE_DEN in
src/board.h) so larger screens get sharp text instead of stretched pixels.
Each font is sized so a capital letter is exactly the wanted height.

Writes src/fonts.h, src/fonts.cpp and a preview image next to this script.

usage: python tools/make_fonts.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src"
FIRST, LAST = 32, 126

SCALES = [(1, 1), (5, 4), (4, 3)]

# (C++ name, ttf file, capital height in pixels at scale 1)
FONTS = [
    ("Font10", "JetBrainsMono-Regular.ttf", 10),
    ("Font22", "JetBrainsMono-Bold.ttf", 22),
    ("Font28", "JetBrainsMono-Bold.ttf", 28),
    ("Font36", "JetBrainsMono-Bold.ttf", 36),
]


def render(font, ch):
    """Return (bitmap rows, width, height, x offset, y offset) for one glyph."""
    size = font.size * 3
    img = Image.new("1", (size, size), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    origin = font.size
    draw.text((origin, origin * 2), ch, font=font, fill=1, anchor="ls")
    box = img.getbbox()
    if box is None:
        return [], 0, 0, 0, 0
    x0, y0, x1, y1 = box
    px = img.load()
    rows = [[1 if px[x, y] else 0 for x in range(x0, x1)] for y in range(y0, y1)]
    return rows, x1 - x0, y1 - y0, x0 - origin, y0 - origin * 2


def pick_size(path, cap):
    """Smallest pixel size whose capital H renders exactly `cap` pixels tall."""
    for ppem in range(cap, cap * 3):
        font = ImageFont.truetype(str(path), ppem)
        if render(font, "H")[2] >= cap:
            return font
    raise SystemExit(f"no size found for {path} at {cap}px")


def pack(rows):
    bits = [b for row in rows for b in row]
    out = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        out.append(int("".join(map(str, chunk)), 2))
    return out


def main():
    cpp = [
        "// Generated by tools/make_fonts.py - do not edit.",
        "// Glyphs rendered from JetBrains Mono (SIL Open Font License 1.1,",
        "// see tools/fonts/OFL.txt).",
        '#include "fonts.h"',
        "",
        "#ifndef HEADLESS",
    ]
    hdr = [
        "// Generated by tools/make_fonts.py - do not edit.",
        "// FontNN is the font for text designed NN pixels tall at 240x135;",
        "// CAPNN is the real height of its capital letters at this board's scale.",
        "#pragma once",
        '#include "board.h"',
        "",
        "#ifndef HEADLESS",
        "#include <TFT_eSPI.h>",
        "",
        "extern const GFXfont Font10;",
        "extern const GFXfont Font22;",
        "extern const GFXfont Font28;",
        "extern const GFXfont Font36;",
        "",
    ]
    previews = []
    for index, (num, den) in enumerate(SCALES):
        guard = f"UI_SCALE_NUM == {num} && UI_SCALE_DEN == {den}"
        keyword = "#if" if index == 0 else "#elif"
        cpp.append(f"{keyword} {guard}")
        hdr.append(f"{keyword} {guard}")
        for name, ttf, base in FONTS:
            cap = (base * num * 2 + den) // (den * 2)  # round half up
            font = pick_size(HERE / "fonts" / ttf, cap)
            advance = round(font.getlength("0"))
            bitmap, glyphs = [], []
            for code in range(FIRST, LAST + 1):
                rows, w, h, xo, yo = render(font, chr(code))
                glyphs.append((len(bitmap), w, h, advance, xo, yo))
                bitmap.extend(pack(rows))
            ascent, descent = font.getmetrics()
            cpp.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{")
            for i in range(0, len(bitmap), 16):
                cpp.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
            cpp.append("};")
            cpp.append(f"static const GFXglyph {name}Glyphs[] PROGMEM = {{")
            for g in glyphs:
                cpp.append("  {%d, %d, %d, %d, %d, %d}," % g)
            cpp.append("};")
            cpp.append(
                f"const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, "
                f"(GFXglyph *){name}Glyphs, {FIRST}, {LAST}, {ascent + descent}}};"
            )
            cpp.append("")
            hdr.append(f"constexpr uint8_t CAP{base} = {cap};")
            print(f"scale {num}/{den} {name}: cap={cap} advance={advance} bytes={len(bitmap)}")
            if index == 0:
                previews.append((font, cap))
    for lines in (cpp, hdr):
        lines.append("#else")
        lines.append('#error "No font set for this UI scale: add it to SCALES in tools/make_fonts.py"')
        lines.append("#endif")
        lines.append("")
        lines.append("#endif  // HEADLESS")

    (SRC / "fonts.cpp").write_text("\n".join(cpp) + "\n", encoding="ascii")
    (SRC / "fonts.h").write_text("\n".join(hdr) + "\n", encoding="ascii")

    img = Image.new("RGB", (480, 260), (11, 14, 17))
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    y = 10
    for (font, cap), text in zip(previews, [
        "ROUTER 1.1.1.1 8.8.8.8 11/16 14:02 1m 12s WIFI 23ms",
        "99.98% 100% 6d 4h", "23 ms 0% 148", "ONLINE OFFLINE",
    ]):
        draw.text((10, y + cap), text, font=font, fill=(232, 237, 242), anchor="ls")
        y += cap + 24
    img = img.resize((960, 520), Image.NEAREST)
    img.save(HERE / "fonts" / "preview.png")


if __name__ == "__main__":
    main()
