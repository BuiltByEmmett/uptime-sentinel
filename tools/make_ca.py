"""Write src/ca_roots.cpp and src/ca_bundle.cpp: the public root certificates
the firmware trusts when it makes HTTPS requests. Roots are copied from the
Mozilla bundle that ships with the `certifi` package. Re-run this if Discord
or one of the default public IP lookup services ever changes its CA, and
before a release to pick up changes to Mozilla's list.

ca_roots.cpp holds two short lists as PEM text. ca_bundle.cpp holds every
Mozilla root in the compact form the ESP32 TLS client can search: for each
root only its subject name and public key, sorted by name. It is used for
addresses the user types in (website checks, ntfy, the generic webhook).

usage: python tools/make_ca.py
"""
import base64
import re
from pathlib import Path

import certifi

# Discord sits behind Cloudflare, which issues from these authorities.
DISCORD = [
    "GTS Root R1",
    "GTS Root R3",
    "GTS Root R4",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
    "SSL.com Root Certification Authority RSA",
    "SSL.com Root Certification Authority ECC",
]

# The public IP lookup URL can be changed in Settings, so that request
# trusts the roots above plus the other authorities most sites use.
LOOKUP = DISCORD + [
    "Amazon Root CA 1",
    "Amazon Root CA 3",
    "USERTrust RSA Certification Authority",
    "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root R46",
    "GlobalSign Root CA - R3",
    "Go Daddy Root Certificate Authority - G2",
    "Starfield Root Certificate Authority - G2",
    "DigiCert Global Root G3",
]

OUT = Path(__file__).resolve().parent.parent / "src" / "ca_roots.cpp"
BUNDLE_OUT = OUT.with_name("ca_bundle.cpp")


def array(name, labels, found):
    lines = ["", f"const char {name}[] ="]
    for label in labels:
        if label not in found:
            raise SystemExit(f"root not found in certifi bundle: {label}")
        lines.append(f"    // {label}")
        for row in found[label].splitlines():
            lines.append(f'    "{row}\\n"')
    lines[-1] += ";"
    return lines


def der_item(data, pos):
    """One DER element at `pos`: (tag, start of content, end of element)."""
    tag = data[pos]
    length = data[pos + 1]
    pos += 2
    if length & 0x80:
        count = length & 0x7F
        length = int.from_bytes(data[pos:pos + count], "big")
        pos += count
    return tag, pos, pos + length


def subject_and_key(der):
    """The subject name and SubjectPublicKeyInfo of a certificate, as DER."""
    _, pos, _ = der_item(der, 0)          # Certificate
    _, pos, _ = der_item(der, pos)        # TBSCertificate
    tag, _, end = der_item(der, pos)
    if tag == 0xA0:                       # [0] version, absent in v1 roots
        pos = end
    fields = []
    for _ in range(6):                    # serial, algorithm, issuer, validity, subject, key
        _, _, end = der_item(der, pos)
        fields.append(der[pos:end])
        pos = end
    return fields[4], fields[5]


def bundle(blocks):
    entries = []
    for _, pem in blocks:
        body = "".join(pem.splitlines()[1:-1])
        entries.append(subject_and_key(base64.b64decode(body)))
    entries.sort(key=lambda e: e[0])
    data = bytearray(len(entries).to_bytes(2, "big"))
    for name, key in entries:
        data += len(name).to_bytes(2, "big") + len(key).to_bytes(2, "big") + name + key
    lines = [
        "// Generated by tools/make_ca.py - do not edit.",
        f"// {len(entries)} public root certificates from Mozilla's list (certifi",
        f"// {certifi.__version__}): subject name and public key of each, sorted by name.",
        '#include "ca_bundle.h"',
        "",
        "const uint8_t CA_BUNDLE[] = {",
    ]
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    lines.append("};")
    with open(BUNDLE_OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} roots ({len(data)} bytes) to {BUNDLE_OUT}")


def main():
    text = Path(certifi.where()).read_text(encoding="utf8")
    blocks = re.findall(
        r'# Label: "(.*?)"\n.*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)',
        text, flags=re.S)
    found = {label: pem for label, pem in blocks}
    lines = [
        "// Generated by tools/make_ca.py - do not edit.",
        "// Public root certificates used to verify HTTPS servers: discord.com for",
        "// alerts, and a wider set for the public IP lookup service.",
        '#include "alerts.h"',
        '#include "pubip.h"',
    ]
    lines += array("DISCORD_ROOT_CAS", DISCORD, found)
    lines += array("LOOKUP_ROOT_CAS", LOOKUP, found)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(DISCORD)} + {len(LOOKUP)} roots to {OUT}")
    bundle(blocks)


if __name__ == "__main__":
    main()
